// Rebuilds the skill catalog in README.md (between the catalog markers). Run: node scripts/catalog.mjs
// With --check it changes nothing and fails when the README is out of date (used in CI).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { skills, summary, ROOT } from "./lib.mjs";

const START = "<!-- catalog:start -->", END = "<!-- catalog:end -->";
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const short = (s, n = 90) => (s.length > n ? s.slice(0, n - 1).replace(/\s+\S*$/, "") + "…" : s);

const rows = skills().filter((s) => s.text).map(summary);
const tools = rows.filter((r) => r.name !== "backboard" && !r.name.startsWith("track-") && r.name !== "sponsor-chains");
const guides = rows.filter((r) => !tools.includes(r));
const type = (r) => (r.type === "Tested" ? `**Tested**${r.tested ? ` ${r.tested}` : ""}` : r.type);
const table = (list) => [
  "| Skill | What it's for | Category | Type | MCP |",
  "| --- | --- | --- | --- | --- |",
  ...list
    .sort((a, b) => (a.category || "~").localeCompare(b.category || "~") || a.title.localeCompare(b.title))
    .map((r) => `| [\`${r.name}\`](skills/${r.name}) | ${cell(short(r.what))} | ${cell(r.category || "–")} | ${type(r)} | ${r.mcp ? "Yes" : ""} |`),
].join("\n");

const block = [
  START,
  `${tools.length} tool skills${guides.length ? ` and ${guides.length} guide skill${guides.length === 1 ? "" : "s"}` : ""}. **Tested** skills were written by hand and their examples run before release; **Generated** skills point your assistant at the tool's own docs, AI docs and MCP server.`,
  "",
  ...(guides.length ? ["**Guides**", "", "| Skill | What it's for |", "| --- | --- |", ...guides.map((r) => `| [\`${r.name}\`](skills/${r.name}) | ${cell(short(r.what, 140))} |`), "", "**Tools**", ""] : []),
  table(tools),
  "",
  "_This table is generated by `node scripts/catalog.mjs`. Don't edit it by hand._",
  END,
].join("\n");

const file = join(ROOT, "README.md"), readme = readFileSync(file, "utf8");
const a = readme.indexOf(START), b = readme.indexOf(END);
if (a < 0 || b < 0) { console.error("README.md is missing the catalog markers"); process.exit(1); }
const next = readme.slice(0, a) + block + readme.slice(b + END.length);
if (process.argv.includes("--check")) {
  if (next !== readme) { console.error("✗ README catalog is out of date. Run: node scripts/catalog.mjs"); process.exit(1); }
  console.log("✓ README catalog is up to date");
} else if (next !== readme) { writeFileSync(file, next); console.log(`Updated the catalog: ${rows.length} skills`); }
else console.log("Catalog already up to date");
